import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const ext = []; const errs = []
page.on('request', r => { const u = new URL(r.url()); if (u.host !== 'localhost:4180' && !u.protocol.startsWith('data') && !u.protocol.startsWith('blob')) ext.push(r.url()) })
page.on('pageerror', e => errs.push(String(e))); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
await page.goto('http://localhost:4180/trial.html')
await page.getByTestId('trial-start').click()
await page.waitForFunction(() => !!document.querySelector('.phaser-host canvas'))
await page.waitForTimeout(1500)
const box = async () => page.locator('.phaser-host canvas').boundingBox()
const toCss = (b, x, y) => ({ x: b.x + (x * b.width) / 1080, y: b.y + (y * b.height) / 1920 })
const tap = async (x, y) => { const b = await box(); const p = toCss(b, x, y); await page.mouse.click(p.x, p.y) }
const b = await box(); const a = toCss(b, 610, 770), c = toCss(b, 640, 1500)
await page.mouse.move(a.x, a.y); await page.mouse.down(); for (let i = 1; i <= 12; i++) await page.mouse.move(a.x + (c.x - a.x) * i / 12, a.y + (c.y - a.y) * i / 12); await page.mouse.up()
await page.waitForTimeout(300)
await page.screenshot({ path: 'shots-trial/1-play.png' })
await tap(362, 356); await page.waitForTimeout(250); await tap(500, 812); await page.waitForTimeout(250); await tap(602, 772)
await page.getByTestId('trial-done').waitFor({ timeout: 15000 })
await page.locator('.trial-share').waitFor({ timeout: 15000 })
await page.waitForTimeout(400)
await page.screenshot({ path: 'shots-trial/2-done.png', fullPage: true })
const ls = await page.evaluate(() => Object.keys(localStorage))
console.log(JSON.stringify({ external: ext, errors: errs, localStorage: ls }))
await browser.close()
