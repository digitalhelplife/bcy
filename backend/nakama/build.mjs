// Build the Nakama JS runtime module into backend/nakama/build/bencaoyou.js
// Nakama's goja runtime requires InitModule and every registered handler to be GLOBAL
// function declarations, so the bundle is an IIFE exposing BCY and thin global wrappers.
import { build } from 'esbuild'
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, 'build/bencaoyou.js')
mkdirSync(dirname(out), { recursive: true })

const res = await build({
  entryPoints: [resolve(here, 'src/main.ts')],
  bundle: true, write: false, format: 'iife', globalName: '__bcy', target: 'es2015',
  platform: 'neutral', minify: false, legalComments: 'none',
  define: { 'import.meta.env.BASE_URL': '"/"', 'import.meta.env': '{}' },
})

const RPCS = {
  'game.bootstrap': ['rpcBootstrap', 'handleRead'],
  'game.state.get': ['rpcStateGet', 'handleRead'],
  'game.run.get': ['rpcRunGet', 'handleRead'],
  'game.request.status': ['rpcRequestStatus', 'handleRead'],
  'game.run.start': ['rpcRunStart', 'handleWrite'],
  'game.run.finish': ['rpcRunFinish', 'handleWrite'],
  'game.run.cancel': ['rpcRunCancel', 'handleWrite'],
  'game.plant.start': ['rpcPlantStart', 'handleWrite'],
  'game.plant.claim': ['rpcPlantClaim', 'handleWrite'],
  'game.garden.save': ['rpcGardenSave', 'handleWrite'],
  'game.tutorial.skip': ['rpcTutorialSkip', 'handleWrite'],
  'game.settings.update': ['rpcSettingsUpdate', 'handleWrite'],
  'game.account.status': ['rpcAccountStatus', 'handleRead'],
  'game.account.delete': ['rpcAccountDelete', 'handleWrite'],
  'game.consent.update': ['rpcConsentUpdate', 'handleWrite'],
  'game.feedback.submit': ['rpcFeedbackSubmit', 'handleWrite'],
  'game.telemetry.track': ['rpcTelemetryTrack', 'handleWrite'],
  'game.playtime.heartbeat': ['rpcPlaytimeHeartbeat', 'handleWrite'],
  'game.season.claim': ['rpcSeasonClaim', 'handleWrite'],
  'game.observe.record': ['rpcObserveRecord', 'handleWrite'],
  'game.quiz.complete': ['rpcQuizComplete', 'handleWrite'],
  'game.craft.make': ['rpcCraftMake', 'handleWrite'],
  'game.challenge.mark': ['rpcChallengeMark', 'handleWrite'],
  'game.plant.care': ['rpcPlantCare', 'handleWrite'],
  'game.transfer.create': ['rpcTransferCreate', 'handleWrite'],
  'game.transfer.claim': ['rpcTransferClaim', 'handleWrite'],
  'game.garden.share.create': ['rpcGardenShareCreate', 'handleWrite'],
  'game.garden.share.revoke': ['rpcGardenShareRevoke', 'handleWrite'],
  'game.garden.share.get': ['rpcGardenShareGet', 'handleRead'],
  'game.garden.share.react': ['rpcGardenShareReact', 'handleWrite'],
}

const polyfills = `
if (!Object.fromEntries) { Object.fromEntries = function (it) { var o = {}; var a = Array.from(it); for (var i = 0; i < a.length; i++) o[a[i][0]] = a[i][1]; return o } }
if (!Object.entries) { Object.entries = function (o) { return Object.keys(o).map(function (k) { return [k, o[k]] }) } }
if (!Object.values) { Object.values = function (o) { return Object.keys(o).map(function (k) { return o[k] }) } }
if (!Array.prototype.includes) { Array.prototype.includes = function (v) { return this.indexOf(v) >= 0 } }
if (!Math.imul) { Math.imul = function (a, b) { var ah = (a >>> 16) & 0xffff, al = a & 0xffff, bh = (b >>> 16) & 0xffff, bl = b & 0xffff; return ((al * bl) + (((ah * bl + al * bh) << 16) >>> 0) | 0) } }
if (!String.prototype.padStart) { String.prototype.padStart = function (n, c) { var s = String(this); c = c || ' '; while (s.length < n) s = c + s; return s } }
`

let code = `// GENERATED by backend/nakama/build.mjs — do not edit. 本草小游记 Nakama module.\n${polyfills}\n${res.outputFiles[0].text}\nvar BCY = __bcy.BCY;\n`
for (const [id, [fn, h]] of Object.entries(RPCS)) {
  code += `function ${fn}(ctx, logger, nk, payload) { return BCY.${h}(${JSON.stringify(id)}, ctx, logger, nk, payload); }\n`
}
code += `function bcyGuardWrite(ctx, logger, nk, data) { return BCY.guardWrite(ctx, logger, nk, data); }\n`
code += `function bcyGuardDelete(ctx, logger, nk, data) { return BCY.guardDelete(ctx, logger, nk, data); }\n`
code += `function bcyBeforeAuthCustom(ctx, logger, nk, data) { return BCY.beforeAuthCustom(ctx, logger, nk, data); }\n`
code += `function bcyBeforeAuthDevice(ctx, logger, nk, data) { return BCY.beforeAuthDevice(ctx, logger, nk, data); }\n`
code += `function bcyBeforeSessionRefresh(ctx, logger, nk, data) { return BCY.beforeSessionRefresh(ctx, logger, nk, data); }\n`
code += `function InitModule(ctx, logger, nk, initializer) {\n  BCY.init(ctx, logger, nk);\n`
for (const [id, [fn]] of Object.entries(RPCS)) code += `  initializer.registerRpc(${JSON.stringify(id)}, ${fn});\n`
code += `  initializer.registerBeforeWriteStorageObjects(bcyGuardWrite);\n  initializer.registerBeforeDeleteStorageObjects(bcyGuardDelete);\n  initializer.registerBeforeAuthenticateCustom(bcyBeforeAuthCustom);\n  initializer.registerBeforeAuthenticateDevice(bcyBeforeAuthDevice);\n  initializer.registerBeforeSessionRefresh(bcyBeforeSessionRefresh);\n`
code += `  logger.info('bencaoyou module loaded: ${Object.keys(RPCS).length} RPCs, config ' + ${JSON.stringify(readFileSync(resolve(here, '../../src/shared/content.ts'), 'utf8').match(/CONFIG_VERSION = '([^']+)'/)[1])});\n}\n`
code += `!InitModule && InitModule.bind(null);\n`
writeFileSync(out, code)
console.log(`wrote ${out} (${(code.length / 1024).toFixed(1)} KiB)`)
